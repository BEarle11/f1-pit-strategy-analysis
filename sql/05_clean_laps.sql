CREATE SCHEMA IF NOT EXISTS F1_PROJECT.ANALYTICS;

CREATE OR REPLACE VIEW F1_PROJECT.ANALYTICS.CLEAN_LAPS AS
WITH laps AS (
    SELECT
        l.*,
        MEDIAN(LAP_TIME_SEC) OVER (PARTITION BY SEASON, RACE_ROUND) AS RACE_MEDIAN_SEC
    FROM F1_PROJECT.RAW.FF1_LAPS l
    WHERE LAP_TIME_SEC IS NOT NULL
)
SELECT
    SEASON, RACE_ROUND, EVENT_NAME,
    DRIVER_NUMBER, DRIVER_CODE, DRIVER_NAME, TEAM,
    LAP_NUMBER, LAP_TIME_SEC,
    STINT, COMPOUND, TYRE_LIFE, FRESH_TYRE,
    LAP_TIME_SEC / RACE_MEDIAN_SEC AS PACE_RATIO  -- 1.00 = race-median pace
FROM laps
WHERE LAP_NUMBER > 1                              -- no standing-start lap
  AND NOT PIT_IN AND NOT PIT_OUT                  -- no pit-lane laps
  AND COMPOUND IN ('SOFT', 'MEDIUM', 'HARD')      -- dry tires only
  AND LAP_TIME_SEC <= RACE_MEDIAN_SEC * 1.07;     -- no safety car / incident laps



  SELECT SEASON,
       COUNT(*) AS CLEAN_LAPS,
       ROUND(100 * COUNT(*) / (SELECT COUNT(*) FROM F1_PROJECT.RAW.FF1_LAPS r
                               WHERE r.SEASON = c.SEASON), 1) AS PCT_KEPT
FROM F1_PROJECT.ANALYTICS.CLEAN_LAPS c
GROUP BY SEASON ORDER BY SEASON;